using System.Collections.Generic;
using System.Linq;
using Storm.SourceGenerator.IR;

namespace Storm.SourceGenerator.Emit;

/// <summary>
/// Emits AST node types and Storm.Runtime support types.
/// Generates one type per rule: sealed record for single-alternative rules,
/// abstract record + sealed subtypes for rules with named alternatives.
/// </summary>
public static class AstEmitter
{
    /// <summary>
    /// Generates the Storm.Runtime types source file (Token, TokenChannel,
    /// SourceSpan, SyntaxNode, etc.).
    /// </summary>
    public static string EmitRuntimeTypes()
    {
        var writer = new CodeWriter();

        writer.WriteLine("// <auto-generated/>");
        writer.WriteLine("#nullable enable");
        writer.WriteEmptyLine();
        writer.WriteLine("using System;");
        writer.WriteLine("using System.Collections.Generic;");
        writer.WriteLine("using System.Collections.Immutable;");
        writer.WriteLine("using System.Linq;");
        writer.WriteEmptyLine();

        writer.WriteBlock("namespace Storm.Runtime", () =>
        {
            // TokenChannel enum
            writer.WriteBlock("public enum TokenChannel", () =>
            {
                writer.WriteLine("Default,");
                writer.WriteLine("Hidden,");
            });
            writer.WriteEmptyLine();

            // SourceSpan
            writer.WriteBlock("public readonly struct SourceSpan", () =>
            {
                writer.WriteLine("public int Start { get; }");
                writer.WriteLine("public int Length { get; }");
                writer.WriteLine("public int End => Start + Length;");
                writer.WriteEmptyLine();
                writer.WriteBlock("public SourceSpan(int start, int length)", () =>
                {
                    writer.WriteLine("Start = start;");
                    writer.WriteLine("Length = length;");
                });
            });
            writer.WriteEmptyLine();

            // LinePosition
            writer.WriteBlock("public readonly struct LinePosition", () =>
            {
                writer.WriteLine("public int Line { get; }");
                writer.WriteLine("public int Column { get; }");
                writer.WriteEmptyLine();
                writer.WriteBlock("public LinePosition(int line, int column)", () =>
                {
                    writer.WriteLine("Line = line;");
                    writer.WriteLine("Column = column;");
                });
            });
            writer.WriteEmptyLine();

            // Token
            writer.WriteBlock("public readonly struct Token", () =>
            {
                writer.WriteLine("public int Kind { get; }");
                writer.WriteLine("public SourceSpan Span { get; }");
                writer.WriteLine("public LinePosition Start { get; }");
                writer.WriteLine("public LinePosition End { get; }");
                writer.WriteLine("public TokenChannel Channel { get; }");
                writer.WriteLine("public string Lexeme { get; }");
                writer.WriteEmptyLine();
                writer.WriteBlock("public Token(int kind, SourceSpan span, LinePosition start, LinePosition end, TokenChannel channel, string lexeme)", () =>
                {
                    writer.WriteLine("Kind = kind;");
                    writer.WriteLine("Span = span;");
                    writer.WriteLine("Start = start;");
                    writer.WriteLine("End = end;");
                    writer.WriteLine("Channel = channel;");
                    writer.WriteLine("Lexeme = lexeme;");
                });
            });
            writer.WriteEmptyLine();

            // SourceText (simple wrapper for generated code to reference)
            writer.WriteBlock("public class SourceText", () =>
            {
                writer.WriteLine("public string Path { get; }");
                writer.WriteLine("public string Contents { get; }");
                writer.WriteEmptyLine();
                writer.WriteBlock("public SourceText(string path, string contents)", () =>
                {
                    writer.WriteLine("Path = path;");
                    writer.WriteLine("Contents = contents;");
                });
            });
            writer.WriteEmptyLine();

            // DiagnosticEntry (structured diagnostic entry for generated code)
            writer.WriteBlock("public readonly struct DiagnosticEntry", () =>
            {
                writer.WriteLine("public string Message { get; }");
                writer.WriteLine("public string? FilePath { get; }");
                writer.WriteLine("public int Line { get; }");
                writer.WriteLine("public int Column { get; }");
                writer.WriteEmptyLine();
                writer.WriteBlock("public DiagnosticEntry(string message, string? filePath, int line, int column)", () =>
                {
                    writer.WriteLine("Message = message;");
                    writer.WriteLine("FilePath = filePath;");
                    writer.WriteLine("Line = line;");
                    writer.WriteLine("Column = column;");
                });
            });
            writer.WriteEmptyLine();

            // DiagnosticBag (structured collection for generated code)
            writer.WriteBlock("public class DiagnosticBag", () =>
            {
                writer.WriteLine("private readonly System.Collections.Generic.List<DiagnosticEntry> _entries = new System.Collections.Generic.List<DiagnosticEntry>();");
                writer.WriteEmptyLine();
                writer.WriteBlock("public void Add(string message, string? filePath, int line, int column)", () =>
                    writer.WriteLine("_entries.Add(new DiagnosticEntry(message, filePath, line, column));"));
                writer.WriteEmptyLine();
                writer.WriteBlock("public void Add(string message)", () =>
                    writer.WriteLine("_entries.Add(new DiagnosticEntry(message, null, 0, 0));"));
                writer.WriteEmptyLine();
                writer.WriteLine("public bool HasErrors => _entries.Count > 0;");
                writer.WriteLine("public int Count => _entries.Count;");
                writer.WriteLine("public System.Collections.Generic.IReadOnlyList<DiagnosticEntry> Entries => _entries;");
                writer.WriteLine("public System.Collections.Generic.IReadOnlyList<string> Messages => _entries.Select(e => e.Message).ToList();");
                writer.WriteEmptyLine();
                writer.WriteBlock("public void TruncateTo(int count)", () => writer.WriteBlock("if (count >= 0 && count < _entries.Count)", () =>
                        writer.WriteLine("_entries.RemoveRange(count, _entries.Count - count);")));
            });
            writer.WriteEmptyLine();

            // StormRuntimeDiagnostic (simple diagnostic for generated lexer/parser)
            writer.WriteBlock("public class StormRuntimeDiagnostic", () =>
            {
                writer.WriteLine("public string Message { get; }");
                writer.WriteEmptyLine();
                writer.WriteBlock("public StormRuntimeDiagnostic(string message)", () => writer.WriteLine("Message = message;"));
            });
            writer.WriteEmptyLine();

            // TokenStream
            writer.WriteBlock("public class TokenStream", () =>
            {
                writer.WriteLine("public SourceText Source { get; }");
                writer.WriteLine("public ImmutableArray<Token> AllTokens { get; }");
                writer.WriteLine("public ImmutableArray<Token> DefaultChannelTokens { get; }");
                writer.WriteEmptyLine();
                writer.WriteBlock("public TokenStream(SourceText source, ImmutableArray<Token> tokens)", () =>
                {
                    writer.WriteLine("Source = source;");
                    writer.WriteLine("AllTokens = tokens;");
                    writer.WriteLine("var defaultBuilder = ImmutableArray.CreateBuilder<Token>();");
                    writer.WriteBlock("foreach (var token in tokens)", () => writer.WriteBlock("if (token.Channel == TokenChannel.Default)", () => writer.WriteLine("defaultBuilder.Add(token);")));
                    writer.WriteLine("DefaultChannelTokens = defaultBuilder.ToImmutable();");
                });
            });
            writer.WriteEmptyLine();

            // SyntaxNode base
            writer.WriteBlock("public abstract class SyntaxNode", () =>
            {
                writer.WriteLine("public SourceSpan Span { get; set; }");
                writer.WriteLine("public SyntaxNode? Parent { get; set; }");
                writer.WriteLine("public Mist.Common.Text.NodeOrigin? Origin { get; set; }");
                writer.WriteLine("public ImmutableArray<Token> LeadingHiddenTokens { get; set; } = ImmutableArray<Token>.Empty;");
                writer.WriteLine("public ImmutableArray<Token> TrailingHiddenTokens { get; set; } = ImmutableArray<Token>.Empty;");
                writer.WriteEmptyLine();
                writer.WriteLine("public abstract IEnumerable<SyntaxNode> Children();");
                writer.WriteEmptyLine();
                writer.WriteLine("/// <summary>");
                writer.WriteLine("/// Walks the tree rooted at this node and sets the Parent property on all descendants.");
                writer.WriteLine("/// Call once after parsing to enable upward traversal.");
                writer.WriteLine("/// </summary>");
                writer.WriteBlock("public void SetParentLinks()", () => writer.WriteBlock("foreach (var child in Children())", () => writer.WriteBlock("if (child is not null)", () =>
                        {
                            writer.WriteLine("child.Parent = this;");
                            writer.WriteLine("child.SetParentLinks();");
                        })));
            });
        });

        return writer.ToString();
    }

    /// <summary>
    /// Generates the AST node types source file for the consumer grammar.
    /// </summary>
    public static string EmitAstNodes(EmissionContext context)
    {
        var writer = new CodeWriter();

        writer.WriteLine("// <auto-generated/>");
        writer.WriteLine("#nullable enable");
        writer.WriteEmptyLine();
        writer.WriteLine("using System;");
        writer.WriteLine("using System.Collections.Generic;");
        writer.WriteLine("using System.Collections.Immutable;");
        writer.WriteLine("using Storm.Runtime;");
        writer.WriteEmptyLine();

        writer.WriteBlock($"namespace {context.ConsumerNamespace}", () =>
        {
            var first = true;
            foreach(var rule in context.Grammar.Rules)
            {
                if(!first)
                {
                    writer.WriteEmptyLine();
                }

                first = false;

                EmitRuleNodeTypes(writer, rule);
            }
        });

        return writer.ToString();
    }

    /// <summary>
    /// Emits the AST node type(s) for a single rule.
    /// </summary>
    private static void EmitRuleNodeTypes(CodeWriter writer, RuleIR rule)
    {
        var hasNamedAlternatives = rule.Alternatives.Any(a => a.AlternativeName != null);

        if(hasNamedAlternatives)
        {
            EmitAbstractNodeWithSubtypes(writer, rule);
        }
        else
        {
            EmitSealedNode(writer, rule);
        }
    }

    /// <summary>
    /// Emits a sealed record for a single-alternative rule (or a rule with no named alternatives).
    /// </summary>
    private static void EmitSealedNode(CodeWriter writer, RuleIR rule)
    {
        var nodeTypeName = rule.Name + "Node";
        var properties = CollectProperties(rule.Alternatives[0]);

        writer.WriteBlock($"public sealed class {nodeTypeName} : SyntaxNode", () =>
        {
            // Properties
            foreach(var prop in properties)
            {
                writer.WriteLine($"public {prop.TypeName} {prop.Name} {{ get; set; }}{prop.DefaultValue}");
            }

            if(properties.Count > 0)
            {
                writer.WriteEmptyLine();
            }

            // Children() override
            writer.WriteBlock("public override IEnumerable<SyntaxNode> Children()", () =>
            {
                var hasChildren = false;
                foreach(var prop in properties)
                {
                    if(prop.IsNodeType && !prop.IsList)
                    {
                        hasChildren = true;
                        if(prop.IsNullable)
                        {
                            writer.WriteBlock($"if ({prop.Name} != null)", () => writer.WriteLine($"yield return {prop.Name};"));
                        }
                        else
                        {
                            writer.WriteLine($"yield return {prop.Name};");
                        }
                    }
                    else if(prop.IsNodeType && prop.IsList)
                    {
                        hasChildren = true;
                        writer.WriteBlock($"foreach (var child in {prop.Name})", () => writer.WriteLine("yield return child;"));
                    }
                }

                if(!hasChildren)
                {
                    writer.WriteLine("yield break;");
                }
            });
        });
    }

    /// <summary>
    /// Emits an abstract record + sealed subtypes for rules with named alternatives.
    /// </summary>
    private static void EmitAbstractNodeWithSubtypes(CodeWriter writer, RuleIR rule)
    {
        var baseNodeTypeName = rule.Name + "Node";

        // Abstract base
        writer.WriteBlock($"public abstract class {baseNodeTypeName} : SyntaxNode", () =>
        {
        });

        // Sealed subtypes for each named alternative
        foreach(var alt in rule.Alternatives)
        {
            writer.WriteEmptyLine();

            var altName = alt.AlternativeName ?? "Default";
            var subtypeName = altName + rule.Name + "Node";
            var properties = CollectProperties(alt);

            writer.WriteBlock($"public sealed class {subtypeName} : {baseNodeTypeName}", () =>
            {
                // Properties
                foreach(var prop in properties)
                {
                    writer.WriteLine($"public {prop.TypeName} {prop.Name} {{ get; set; }}{prop.DefaultValue}");
                }

                if(properties.Count > 0)
                {
                    writer.WriteEmptyLine();
                }

                // Children() override
                writer.WriteBlock("public override IEnumerable<SyntaxNode> Children()", () =>
                {
                    var hasChildren = false;
                    foreach(var prop in properties)
                    {
                        if(prop.IsNodeType && !prop.IsList)
                        {
                            hasChildren = true;
                            if(prop.IsNullable)
                            {
                                writer.WriteBlock($"if ({prop.Name} != null)", () => writer.WriteLine($"yield return {prop.Name};"));
                            }
                            else
                            {
                                writer.WriteLine($"yield return {prop.Name};");
                            }
                        }
                        else if(prop.IsNodeType && prop.IsList)
                        {
                            hasChildren = true;
                            writer.WriteBlock($"foreach (var child in {prop.Name})", () => writer.WriteLine("yield return child;"));
                        }
                    }

                    if(!hasChildren)
                    {
                        writer.WriteLine("yield break;");
                    }
                });
            });
        }
    }

    /// <summary>
    /// Collects the properties for an alternative's AST node type.
    /// </summary>
    private static List<PropertyInfo> CollectProperties(RuleAlternativeIR alt)
    {
        var properties = new List<PropertyInfo>();
        var usedNames = new HashSet<string>();

        // Build a set of TokenRefIR expressions that live inside a ZeroOrMoreIR
        // or OneOrMoreIR so we can promote labeled tokens to list properties.
        // Only tokens need this — rule refs inside repetitions already get a
        // separate ImmutableArray property via the unlabeled-property walk.
        var tokensInsideRepetition = new HashSet<ExpressionIR>();
        CollectTokensInsideRepetition(alt.Expression, false, tokensInsideRepetition);

        // Build a set of expressions that live inside an OptionalIR so we can
        // make labeled token fields nullable (Token?) when they may not be set.
        var exprsInsideOptional = new HashSet<ExpressionIR>();
        CollectExpressionsInsideOptional(alt.Expression, false, exprsInsideOptional);

        // First, add properties from field labels
        foreach(var label in alt.FieldLabels)
        {
            var propName = PascalCase(label.Label);
            propName = EnsureUnique(propName, usedNames);
            PropertyInfo propInfo;
            if(tokensInsideRepetition.Contains(label.Expression))
            {
                // The labeled token is inside a * or + repetition — generate a list property
                propInfo = new PropertyInfo(propName, "ImmutableArray<Token>", false, false, true, " = ImmutableArray<Token>.Empty;");
            }
            else if(exprsInsideOptional.Contains(label.Expression))
            {
                // The labeled expression is inside an optional group — make it nullable
                propInfo = GetPropertyInfo(label.Expression, propName) switch
                {
                    var p when p.TypeName == "Token" => new PropertyInfo(propName, "Token?", true, false, false, ""),
                    var p when !p.IsNullable && p.IsNodeType => new PropertyInfo(propName, p.TypeName + "?", true, true, false, ""),
                    var p => p,
                };
            }
            else
            {
                propInfo = GetPropertyInfo(label.Expression, propName);
            }

            properties.Add(propInfo);
        }

        // Then, walk the expression to find unlabeled elements
        CollectUnlabeledProperties(alt.Expression, alt.FieldLabels, properties, usedNames);

        return properties;
    }

    /// <summary>
    /// Recursively walks the expression tree and adds all <see cref="TokenRefIR"/>
    /// sub-expressions that are nested inside a <see cref="ZeroOrMoreIR"/> or
    /// <see cref="OneOrMoreIR"/> to the <paramref name="result"/> set.
    /// Only tokens need promotion — rule refs already get separate list properties.
    /// </summary>
    private static void CollectTokensInsideRepetition(ExpressionIR expr, bool insideRep, HashSet<ExpressionIR> result)
    {
        if(insideRep && expr is TokenRefIR)
        {
            _ = result.Add(expr);
        }

        switch(expr)
        {
            case SequenceIR seq:
                foreach(var elem in seq.Elements)
                {
                    CollectTokensInsideRepetition(elem, insideRep, result);
                }

                break;
            case AlternationIR alt:
                foreach(var a in alt.Alternatives)
                {
                    CollectTokensInsideRepetition(a, insideRep, result);
                }

                break;
            case OptionalIR opt:
                CollectTokensInsideRepetition(opt.Inner, insideRep, result);
                break;
            case ZeroOrMoreIR zom:
                CollectTokensInsideRepetition(zom.Inner, true, result);
                break;
            case OneOrMoreIR oom:
                CollectTokensInsideRepetition(oom.Inner, true, result);
                break;
        }
    }

    /// <summary>
    /// Recursively walks the expression tree and adds all sub-expressions that
    /// are nested inside an <see cref="OptionalIR"/> to the <paramref name="result"/> set.
    /// This allows labeled fields inside optional groups to be made nullable.
    /// Only collects TokenRefIR and AlternationIR (token choices) — not rule refs
    /// or sequences, which are already handled by other nullable logic.
    /// </summary>
    private static void CollectExpressionsInsideOptional(ExpressionIR expr, bool insideOpt, HashSet<ExpressionIR> result)
    {
        if(insideOpt && (expr is TokenRefIR || expr is AlternationIR))
        {
            _ = result.Add(expr);
        }

        switch(expr)
        {
            case SequenceIR seq:
                foreach(var elem in seq.Elements)
                {
                    CollectExpressionsInsideOptional(elem, insideOpt, result);
                }

                break;
            case AlternationIR alt:
                foreach(var a in alt.Alternatives)
                {
                    CollectExpressionsInsideOptional(a, insideOpt, result);
                }

                break;
            case OptionalIR opt:
                CollectExpressionsInsideOptional(opt.Inner, true, result);
                break;
            case ZeroOrMoreIR zom:
                CollectExpressionsInsideOptional(zom.Inner, insideOpt, result);
                break;
            case OneOrMoreIR oom:
                CollectExpressionsInsideOptional(oom.Inner, insideOpt, result);
                break;
        }
    }

    /// <summary>
    /// Walks an expression to find elements that don't have field labels
    /// and generates auto-named properties for them.
    /// </summary>
    private static void CollectUnlabeledProperties(
        ExpressionIR expr,
        IReadOnlyList<FieldLabelIR> labels,
        List<PropertyInfo> properties,
        HashSet<string> usedNames)
    {
        // Skip expressions that are already covered by field labels
        if(labels.Any(l => ReferenceEquals(l.Expression, expr)))
        {
            return;
        }

        switch(expr)
        {
            case SequenceIR seq:
                foreach(var element in seq.Elements)
                {
                    CollectUnlabeledProperties(element, labels, properties, usedNames);
                }

                break;

            case TokenRefIR tokenRef:
                if(!labels.Any(l => ReferenceEquals(l.Expression, expr)))
                {
                    var propName = PascalCase(tokenRef.Token.Name);
                    propName = EnsureUnique(propName, usedNames);
                    properties.Add(new PropertyInfo(propName, "Token", false, false, false, " = default;"));
                }

                break;

            case RuleRefIR ruleRef:
                if(!labels.Any(l => ReferenceEquals(l.Expression, expr)))
                {
                    var propName = PascalCase(ruleRef.Rule.Name);
                    propName = EnsureUnique(propName, usedNames);
                    var typeName = ruleRef.Rule.Name + "Node";
                    properties.Add(new PropertyInfo(propName, typeName, false, true, false, " = default!;"));
                }

                break;

            case OptionalIR opt:
                // The inner expression becomes nullable
                var optProp = GetPropertyInfoForOptional(opt.Inner, usedNames);
                if(optProp != null && !labels.Any(l => ReferenceEquals(l.Expression, opt)))
                {
                    properties.Add(optProp);
                }

                break;

            case ZeroOrMoreIR zom:
                var zomProp = GetPropertyInfoForList(zom.Inner, usedNames);
                if(zomProp != null && !labels.Any(l => ReferenceEquals(l.Expression, zom)))
                {
                    properties.Add(zomProp);
                }

                break;

            case OneOrMoreIR oom:
                var oomProp = GetPropertyInfoForList(oom.Inner, usedNames);
                if(oomProp != null && !labels.Any(l => ReferenceEquals(l.Expression, oom)))
                {
                    properties.Add(oomProp);
                }

                break;

            case AlternationIR alt:
                // For unlabeled alternations at non-top level, we don't auto-generate properties
                break;

            default:
                break;
        }
    }

    private static PropertyInfo GetPropertyInfo(ExpressionIR expr, string propName)
    {
        return expr switch
        {
            TokenRefIR => new PropertyInfo(propName, "Token", false, false, false, " = default;"),
            RuleRefIR ruleRef => new PropertyInfo(propName, ruleRef.Rule.Name + "Node", false, true, false, " = default!;"),
            OptionalIR opt => GetPropertyInfoForOptionalInner(opt.Inner, propName),
            ZeroOrMoreIR zom => GetPropertyInfoForListInner(zom.Inner, propName),
            OneOrMoreIR oom => GetPropertyInfoForListInner(oom.Inner, propName),
            _ => new PropertyInfo(propName, "Token", false, false, false, " = default;"),
        };
    }

    private static PropertyInfo? GetPropertyInfoForOptional(ExpressionIR inner, HashSet<string> usedNames)
    {
        switch(inner)
        {
            case TokenRefIR tokenRef:
                {
                    var name = EnsureUnique(PascalCase(tokenRef.Token.Name), usedNames);
                    return new PropertyInfo(name, "Token?", true, false, false, "");
                }
            case RuleRefIR ruleRef:
                {
                    var name = EnsureUnique(PascalCase(ruleRef.Rule.Name), usedNames);
                    return new PropertyInfo(name, ruleRef.Rule.Name + "Node?", true, true, false, "");
                }
            case SequenceIR seq:
                {
                    var seqRuleRef = seq.Elements.OfType<RuleRefIR>().FirstOrDefault();
                    if(seqRuleRef != null)
                    {
                        var name = EnsureUnique(PascalCase(seqRuleRef.Rule.Name), usedNames);
                        return new PropertyInfo(name, seqRuleRef.Rule.Name + "Node?", true, true, false, "");
                    }

                    var seqTokenRef = seq.Elements.OfType<TokenRefIR>().LastOrDefault();
                    if(seqTokenRef != null)
                    {
                        var name = EnsureUnique(PascalCase(seqTokenRef.Token.Name), usedNames);
                        return new PropertyInfo(name, "Token?", true, false, false, "");
                    }

                    return null;
                }
            default:
                return null;
        }
    }

    private static PropertyInfo GetPropertyInfoForOptionalInner(ExpressionIR inner, string propName)
    {
        return inner switch
        {
            TokenRefIR => new PropertyInfo(propName, "Token?", true, false, false, ""),
            RuleRefIR ruleRef => new PropertyInfo(propName, ruleRef.Rule.Name + "Node?", true, true, false, ""),
            SequenceIR seq => GetPropertyInfoForOptionalSequence(seq, propName),
            _ => new PropertyInfo(propName, "Token?", true, false, false, ""),
        };
    }

    private static PropertyInfo GetPropertyInfoForOptionalSequence(SequenceIR seq, string propName)
    {
        var seqRuleRef = seq.Elements.OfType<RuleRefIR>().FirstOrDefault();
        if(seqRuleRef != null)
        {
            return new PropertyInfo(propName, seqRuleRef.Rule.Name + "Node?", true, true, false, "");
        }

        return new PropertyInfo(propName, "Token?", true, false, false, "");
    }

    private static PropertyInfo? GetPropertyInfoForList(ExpressionIR inner, HashSet<string> usedNames)
    {
        switch(inner)
        {
            case TokenRefIR tokenRef:
                {
                    var name = EnsureUnique(PascalCase(tokenRef.Token.Name) + "s", usedNames);
                    return new PropertyInfo(name, "ImmutableArray<Token>", false, false, true, " = ImmutableArray<Token>.Empty;");
                }
            case RuleRefIR ruleRef:
                {
                    var name = EnsureUnique(PascalCase(ruleRef.Rule.Name) + "s", usedNames);
                    var elementType = ruleRef.Rule.Name + "Node";
                    return new PropertyInfo(name, $"ImmutableArray<{elementType}>", false, true, true, $" = ImmutableArray<{elementType}>.Empty;");
                }
            case SequenceIR seq:
                {
                    var seqRuleRef = seq.Elements.OfType<RuleRefIR>().FirstOrDefault();
                    if(seqRuleRef != null)
                    {
                        var name = EnsureUnique(PascalCase(seqRuleRef.Rule.Name) + "s", usedNames);
                        var elementType = seqRuleRef.Rule.Name + "Node";
                        return new PropertyInfo(name, $"ImmutableArray<{elementType}>", false, true, true, $" = ImmutableArray<{elementType}>.Empty;");
                    }

                    var seqTokenRef = seq.Elements.OfType<TokenRefIR>().LastOrDefault();
                    if(seqTokenRef != null)
                    {
                        var name = EnsureUnique(PascalCase(seqTokenRef.Token.Name) + "s", usedNames);
                        return new PropertyInfo(name, "ImmutableArray<Token>", false, false, true, " = ImmutableArray<Token>.Empty;");
                    }

                    return null;
                }
            default:
                return null;
        }
    }

    private static PropertyInfo GetPropertyInfoForListInner(ExpressionIR inner, string propName)
    {
        switch(inner)
        {
            case TokenRefIR:
                return new PropertyInfo(propName, "ImmutableArray<Token>", false, false, true, " = ImmutableArray<Token>.Empty;");
            case RuleRefIR ruleRef:
                {
                    var elementType = ruleRef.Rule.Name + "Node";
                    return new PropertyInfo(propName, $"ImmutableArray<{elementType}>", false, true, true, $" = ImmutableArray<{elementType}>.Empty;");
                }
            case SequenceIR seq:
                {
                    var seqRuleRef = seq.Elements.OfType<RuleRefIR>().FirstOrDefault();
                    if(seqRuleRef != null)
                    {
                        var elementType = seqRuleRef.Rule.Name + "Node";
                        return new PropertyInfo(propName, $"ImmutableArray<{elementType}>", false, true, true, $" = ImmutableArray<{elementType}>.Empty;");
                    }

                    return new PropertyInfo(propName, "ImmutableArray<Token>", false, false, true, " = ImmutableArray<Token>.Empty;");
                }
            default:
                return new PropertyInfo(propName, "ImmutableArray<Token>", false, false, true, " = ImmutableArray<Token>.Empty;");
        }
    }

    private static string PascalCase(string name)
    {
        return string.IsNullOrEmpty(name) ? "Value" : char.ToUpperInvariant(name[0]) + name.Substring(1);
    }

    private static string EnsureUnique(string name, HashSet<string> usedNames)
    {
        var candidate = name;
        var suffix = 2;
        while(!usedNames.Add(candidate))
        {
            candidate = name + suffix;
            suffix++;
        }

        return candidate;
    }

    /// <summary>
    /// Describes a property on a generated AST node type.
    /// </summary>
    private sealed class PropertyInfo
    {
        public string Name { get; }
        public string TypeName { get; }
        public bool IsNullable { get; }
        public bool IsNodeType { get; }
        public bool IsList { get; }
        public string DefaultValue { get; }

        public PropertyInfo(string name, string typeName, bool isNullable, bool isNodeType, bool isList, string defaultValue)
        {
            Name = name;
            TypeName = typeName;
            IsNullable = isNullable;
            IsNodeType = isNodeType;
            IsList = isList;
            DefaultValue = defaultValue;
        }
    }
}