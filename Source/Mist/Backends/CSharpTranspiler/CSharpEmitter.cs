using Mist.Common.Diagnostics;
using Mist.Semantics.Contracts;

namespace Mist.Backends.CSharpTranspiler;

/// <summary>
/// Walks the semantic model and emits C# source files into the output directory.
/// Symbols are processed in deterministic order (sorted by fully-qualified name).
/// </summary>
public sealed class CSharpEmitter
{
    public static void Emit(ISemanticModel model, string outputDirectory, DiagnosticBag diagnostics)
    {
        Directory.CreateDirectory(outputDirectory);

        // Emit a .csproj file with deterministic build settings
        var csprojPath = Path.Combine(outputDirectory, "MistOutput.csproj");
        var csprojContent = """
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup>
                <OutputType>Exe</OutputType>
                <TargetFramework>net10.0</TargetFramework>
                <ImplicitUsings>enable</ImplicitUsings>
                <Nullable>enable</Nullable>
                <Deterministic>true</Deterministic>
              </PropertyGroup>
            </Project>
            """;
        File.WriteAllText(csprojPath, csprojContent);

        // Walk symbols in deterministic order and emit C# source files.
        // Concrete emission logic is deferred to the Mist-language spec.
        var symbols = model.AllSymbols
            .OrderBy(s => s.Name, StringComparer.Ordinal)
            .ToList();

        // TODO: Emit one .cs file per top-level declaration once the
        // Mist language spec defines concrete syntax and semantics.
        // For now, emit a minimal Program.cs stub.
        var programPath = Path.Combine(outputDirectory, "Program.cs");
        File.WriteAllText(programPath, """
            // Auto-generated by the Mist C# transpiler backend.
            Console.WriteLine("Hello from Mist!");
            """);
    }
}
